      AND f.status = 'active'
);

UPDATE "user" u
SET storage_used = x.total_size
FROM (
    SELECT owner_id AS user_id, COALESCE(SUM(file_size), 0) AS total_size
    FROM "file"
    WHERE status = 'active'
    GROUP BY owner_id
) x
WHERE u.user_id = x.user_id;

UPDATE "user" u
SET storage_used = 0
WHERE NOT EXISTS (
    SELECT 1
    FROM "file" f
    WHERE f.owner_id = u.user_id
      AND f.status = 'active'
);

