            PERFORM recalc_folder_cached_size(NEW.parent_folder_id);
        END IF;
        RETURN NULL;
    ELSE
        PERFORM recalc_folder_cached_size(OLD.parent_folder_id);
        RETURN NULL;
    END IF;
END;
$$ LANGUAGE plpgsql;

